// Determine if a hex color is light or dark
export function isLightColor(hex) {
  if (!hex || typeof hex !== 'string') return false
  const cleanHex = hex.replace('#', '')
  if (cleanHex.length < 6) return false
  const r = parseInt(cleanHex.substring(0, 2), 16)
  const g = parseInt(cleanHex.substring(2, 4), 16)
  const b = parseInt(cleanHex.substring(4, 6), 16)
  // Perceived brightness formula
  const brightness = (r * 299 + g * 587 + b * 114) / 1000
  return brightness > 140
}

// Generate complete custom theme based on baseBg, accentColor, and meshBaseColor
export function createCustomTheme(baseBg, accentColor, meshBaseColor) {
  const isLight = isLightColor(baseBg)

  return {
    id: 'custom',
    name: 'Custom Palette',
    badge: 'Custom',
    baseBg: baseBg,
    bgGradient: isLight
      ? `radial-gradient(ellipse 90% 70% at 50% 30%, ${baseBg}ee 0%, ${baseBg}aa 50%, ${baseBg} 100%)`
      : `radial-gradient(ellipse 90% 70% at 50% 30%, ${baseBg} 0%, #000000 100%)`,
    accentColor: accentColor,
    accentSecondary: accentColor,
    accentGlow: `${accentColor}44`,
    meshBaseColor: meshBaseColor,
    textMain: isLight ? '#0f172a' : '#f8fafc',
    textBody: isLight ? '#334155' : '#cbd5e1',
    textMuted: isLight ? '#64748b' : '#94a3b8',
    glassBg: isLight ? 'rgba(255, 255, 255, 0.90)' : 'rgba(15, 23, 42, 0.85)',
    glassBorder: `${accentColor}40`,
    glassHoverBg: isLight ? 'rgba(255, 255, 255, 0.98)' : 'rgba(24, 34, 58, 0.95)',
    inputBg: isLight ? '#ffffff' : 'rgba(15, 23, 42, 0.8)',
    cardShadow: isLight
      ? `0 14px 40px -10px ${accentColor}20, 0 2px 12px 0 rgba(0, 0, 0, 0.05)`
      : `0 14px 40px -10px rgba(0, 0, 0, 0.7), 0 2px 12px 0 ${accentColor}15`,
    blueprintColor: `${accentColor}12`,
    isDark: !isLight
  }
}

// Apply theme CSS variables to :root document element
export function applyThemeVariables(theme) {
  if (typeof document === 'undefined') return
  const root = document.documentElement
  root.style.setProperty('--base-bg', theme.baseBg)
  root.style.setProperty('--bg-gradient', theme.bgGradient)
  root.style.setProperty('--accent-color', theme.accentColor)
  root.style.setProperty('--accent-secondary', theme.accentSecondary)
  root.style.setProperty('--accent-glow', theme.accentGlow)
  root.style.setProperty('--mesh-base-color', theme.meshBaseColor)
  root.style.setProperty('--text-main', theme.textMain)
  root.style.setProperty('--text-body', theme.textBody)
  root.style.setProperty('--text-muted', theme.textMuted)
  root.style.setProperty('--glass-bg', theme.glassBg)
  root.style.setProperty('--glass-border', theme.glassBorder)
  root.style.setProperty('--glass-hover-bg', theme.glassHoverBg)
  root.style.setProperty('--input-bg', theme.inputBg)
  root.style.setProperty('--card-shadow', theme.cardShadow)
  root.style.setProperty('--blueprint-color', theme.blueprintColor)

  if (theme.isDark) {
    root.classList.add('dark')
  } else {
    root.classList.remove('dark')
  }
}
